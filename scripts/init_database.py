"""Initialize the Ember Atlas PostgreSQL database: migrations, verified ingestion, record-count validation.

    export DATABASE_URL='postgresql+psycopg://USER:PASSWORD@127.0.0.1:5432/ember_atlas'
    python scripts/init_database.py            # idempotent: an already-loaded release is detected, never overwritten
    python scripts/init_database.py --schema   # also rewrite database/schema/schema.sql (offline SQL of all migrations)

Steps: (1) alembic upgrade head (database/migrations); (2) app.ingestion loads dataset/processed after verifying every
hash pinned in dataset/metadata/baseline.json, including the restored reference documents; (3) table counts are
compared with expected_database_counts in dataset/metadata/manifest.json.
"""
import argparse
import contextlib
import io
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / 'backend'), str(ROOT)]


def alembic_config():
    from alembic.config import Config
    return Config(str(ROOT / 'database/alembic.ini'))


def write_schema_sql():
    from alembic import command
    buffer = io.StringIO()
    config = alembic_config()
    config.output_buffer = buffer
    with contextlib.redirect_stdout(buffer):
        command.upgrade(config, 'head', sql=True)
    out = ROOT / 'database/schema/schema.sql'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('-- Generated by `python scripts/init_database.py --schema` (alembic upgrade head --sql). Do not edit by hand.\n'
                   + buffer.getvalue())
    print('wrote', out.relative_to(ROOT))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--schema', action='store_true', help='rewrite database/schema/schema.sql')
    args = parser.parse_args()
    if args.schema:
        write_schema_sql()
    if not os.environ.get('DATABASE_URL'):
        sys.exit('Set DATABASE_URL (see .env.example), e.g. postgresql+psycopg://ember_atlas:PASSWORD@127.0.0.1:5432/ember_atlas')
    from alembic import command
    command.upgrade(alembic_config(), 'head')
    from app.ingestion import ingest
    from ember_atlas.paths import MANIFEST
    result = ingest()
    expected = json.loads(MANIFEST.read_text())['expected_database_counts']
    counts = result['counts']
    mismatches = {k: (v, counts.get(k)) for k, v in expected.items() if counts.get(k) != v}
    print(json.dumps({'status': result['status'], 'dataset_version': result.get('dataset_version'),
                      'counts': {k: counts.get(k) for k in expected}}, indent=1))
    if mismatches:
        sys.exit(f'Record counts differ from dataset/metadata/manifest.json: {mismatches}')
    print('database OK: record counts match the dataset manifest')


if __name__ == '__main__':
    main()
