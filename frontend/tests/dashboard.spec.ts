test('selects actual records and overlays compatible source-linked measurements',async({page})=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
 await page.goto('/#/records')
 await page.getByRole('checkbox',{name:'Select comparison record row 2',exact:true}).check()
 await page.getByRole('checkbox',{name:'Select comparison record row 4',exact:true}).check()
 const comparison=page.getByRole('region',{name:'Source record comparison',exact:true})
 await expect(comparison.getByText('2/8 selected',{exact:true})).toBeVisible()
 const select=comparison.getByLabel('Comparison parameter')
 await expect(select.locator('option').filter({hasText:'fuel_sccm'})).toHaveCount(1)
 const value=await select.locator('option').filter({hasText:'fuel_sccm'}).getAttribute('value')
 await select.selectOption(value!)
 await expect(comparison.locator('.js-plotly-plot')).toBeVisible()
 await expect(comparison.locator('.scatterlayer .trace')).toHaveCount(2)
 await expect(comparison.locator('.ytitle')).toHaveText('sccm')
 await expect(comparison).toContainText('not independent experiments')
 await expect(comparison.getByRole('table')).toContainText('103.8 sccm')
 await expect(comparison.getByRole('table')).toContainText('uncertainty not reported')
 await comparison.getByTestId('scientific-plot').scrollIntoViewIfNeeded()
 const point=await comparison.locator('.scatterlayer .point').first().boundingBox()
 expect(point).not.toBeNull()
 await page.mouse.click(point!.x+point!.width/2,point!.y+point!.height/2)
 await expect(page.getByRole('region',{name:'Source record details'})).toContainText('Spice.csv')
 await page.getByRole('button',{name:'Close record details'}).click()
 await comparison.screenshot({path:'../assets/screenshots/legacy_MVP_comparison.png'})
 await comparison.getByRole('button',{name:'Clear selection'}).click()
 await expect(comparison.getByText('0/8 selected',{exact:true})).toBeVisible()
 expect(errors).toEqual([])
})

test('explores deterministic indexed gaps and traces cell counts to source evidence',async({page})=>{
 await page.goto('/#/records')
 const coverage=page.getByRole('region',{name:'Research gap explorer',exact:true})
 await expect(coverage.getByRole('table',{name:'Indexed coverage matrix'})).toBeVisible()
 await expect(coverage.locator('.coverage-summary')).toContainText('469 source records')
 await expect(coverage).toContainText('34 exact repeats retained')
 await expect(coverage).toContainText('does not prove an experiment has never occurred')
 await coverage.locator('.coverage-cell.observed').first().click()
 await coverage.getByRole('button',{name:'Inspect source 1',exact:true}).click()
 await expect(page.getByRole('region',{name:'Source record details'})).toContainText('SHA-256')
 await page.getByRole('button',{name:'Close record details'}).click()
 await coverage.screenshot({path:'../assets/screenshots/legacy_MVP_coverage.png'})
 await page.getByRole('navigation',{name:'Investigations'}).getByRole('button',{name:/FLEX/}).click()
 const vertical=coverage.getByLabel('Coverage vertical parameter')
 await expect(vertical.locator('option').filter({hasText:'Ambient pressure; mmHg'})).toHaveCount(1)
 const pressure=await vertical.locator('option').filter({hasText:'Ambient pressure; mmHg'}).getAttribute('value')
 await vertical.selectOption(pressure!)
 await expect(coverage.locator('.coverage-summary')).toContainText('1 unusable metadata')
 await coverage.getByLabel('Coverage horizontal parameter').selectOption(pressure!)
 await expect(coverage.getByRole('alert')).toContainText('Choose two different coverage fields')
 await expect(page.getByRole('heading',{name:'Investigation observatory'})).toBeVisible()
})
