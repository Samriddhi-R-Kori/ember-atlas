import { test,expect } from '@playwright/test'
test('browses real records, filters and opens source-linked observations',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/#/records')
 await expect(page.getByRole('heading',{name:'Investigation observatory'})).toBeVisible()
 await expect(page.getByText('1,068',{exact:true})).toBeVisible()
 await expect(page.getByText('Scientific approval pending')).toHaveCount(0)
 await expect(page.locator('.js-plotly-plot')).toBeVisible()
 await page.screenshot({path:'../assets/screenshots/legacy_MVP_dashboard_desktop.png',fullPage:true})
 await page.getByRole('navigation',{name:'Investigations'}).getByRole('button',{name:/FLEX/}).click()
 await page.getByRole('textbox',{name:'Search source records'}).fill('C11M201')
 await page.getByRole('button',{name:'View source record 114',exact:true}).click()
 const detail=page.getByRole('region',{name:'Source record details'})
 await expect(detail).toBeVisible()
 await expect(detail.getByText('Withheld — disputed')).toBeVisible()
 await expect(detail.getByRole('link',{name:'NASA evidence source'})).toHaveAttribute('href',/https:\/\/psi.nasa.gov/)
 await expect(detail.getByText('SHA-256',{exact:true})).toBeVisible()
 await expect(detail).toContainText('Uncertainty: not reported')
 await page.getByRole('button',{name:'Close record details'}).click()
 await expect(detail).not.toBeVisible()
 expect(errors).toEqual([])
})
test('renders Plotly, omits disputed pressure and inspects workbook candidates',async({page})=>{
 await page.goto('/#/records')
 await page.getByRole('navigation',{name:'Investigations'}).getByRole('button',{name:/FLEX/}).click()
 const select=page.getByLabel('Scientific parameter')
 await expect(select.locator('option')).not.toHaveCount(0)
 const value=await select.locator('option').filter({hasText:'Ambient pressure; mmHg'}).getAttribute('value')
 await select.selectOption(value!)
 await expect(page.locator('.js-plotly-plot')).toBeVisible()
 await expect(page.locator('.ytitle')).toHaveText('Pa')
 const point=await page.locator('.scatterlayer .point').first().boundingBox()
 expect(point).not.toBeNull()
 await page.mouse.click(point!.x+point!.width/2,point!.y+point!.height/2)
 await expect(page.getByRole('region',{name:'Source record details'})).toBeVisible()
 await page.getByRole('button',{name:'Close record details'}).click()
 await expect(page.getByText(/missing, unsupported or disputed values omitted/)).toBeVisible()
 await page.getByRole('navigation',{name:'Investigations'}).getByRole('button',{name:/SPICE/}).click()
 await page.getByRole('button',{name:'Workbook records',exact:true}).click()
 await expect(page.getByText('648 records',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:/View source record/}).first().click()
 await expect(page.getByRole('region',{name:'Source record details'})).toContainText('no scientific merge approved')
})
